/* Regenerates the three demo React components from the standalone HTML sources in this folder.
 * Usage:  node demo-src/build-demos.js   (run from the cardping-website repo root or anywhere)
 * Each component = scoped <style> + server-rendered markup (dangerouslySetInnerHTML) +
 * the standalone demo <script> run once client-side via new Function() in a useEffect.
 * After running, `npm run build` to verify, then deploy (see demo-src/HANDOFF.md).
 */
const fs = require("fs");
const path = require("path");
const HERE = __dirname;
const COMPONENTS = path.join(HERE, "..", "components");
const PUBLIC = path.join(HERE, "..", "public");

// ---- CSS scoping helpers ----
function splitTopLevel(css) {
  const out = []; let d = 0, s = 0;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === "{") d++;
    else if (c === "}") { d--; if (d === 0) { out.push(css.slice(s, i + 1)); s = i + 1; } }
  }
  const t = css.slice(s).trim(); if (t) out.push(t);
  return out;
}
function prefixSel(list, scope) {
  return list.split(",").map(x => {
    x = x.trim(); if (!x) return x;
    if (x === ":root") return scope;
    if (x.startsWith(":root")) return scope + x.slice(5);
    if (x === "html" || x === "body") return scope;
    return scope + " " + x;
  }).join(", ");
}
function scopeRules(chunk, scope) {
  return splitTopLevel(chunk).map(b => {
    b = b.trim(); if (!b) return "";
    const i = b.indexOf("{"); if (i === -1) return b;
    return prefixSel(b.slice(0, i).trim(), scope) + " " + b.slice(i);
  }).join("\n");
}
function scopeCss(css, scope, kfPrefix) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const kf = [];
  let out = splitTopLevel(css).map(block => {
    const b = block.trim(); if (!b) return "";
    if (b.startsWith("@keyframes")) {
      const m = b.match(/^@keyframes\s+([A-Za-z0-9_-]+)/);
      if (m) { const nn = kfPrefix + "_" + m[1]; kf.push([m[1], nn]); return b.replace(/^@keyframes\s+[A-Za-z0-9_-]+/, "@keyframes " + nn); }
      return b;
    }
    if (b.startsWith("@media") || b.startsWith("@supports")) {
      const o = b.indexOf("{");
      return b.slice(0, o).trim() + " {\n" + scopeRules(b.slice(o + 1, b.lastIndexOf("}")), scope) + "\n}";
    }
    if (b.startsWith("@")) return b;
    const i = b.indexOf("{");
    return prefixSel(b.slice(0, i).trim(), scope) + " " + b.slice(i);
  }).join("\n");
  kf.sort((a, b) => b[0].length - a[0].length);
  for (const [n, nn] of kf) out = out.replace(new RegExp("\\b" + n + "\\b", "g"), nn);
  return out;
}
function stripGlobalBody(css) {
  return splitTopLevel(css).filter(b => {
    b = b.trim(); const i = b.indexOf("{"); if (i === -1) return true;
    const sel = b.slice(0, i).trim().replace(/\s+/g, " ");
    return !(sel === "body" || sel === "html, body" || sel === "html,body" || sel === "html");
  }).join("\n");
}
function extract(file) {
  const html = fs.readFileSync(file, "utf8");
  const css = html.match(/<style>([\s\S]*?)<\/style>/)[1];
  const script = (html.match(/<script>([\s\S]*?)<\/script>/) || [null, ""])[1];
  const after = html.slice(html.indexOf("</style>") + 8);
  const si = after.indexOf("<script>");
  const markup = (si === -1 ? after : after.slice(0, si)).trim();
  return { css, markup, script };
}
function emit(name, wrapperClass, css, markup, script) {
  return `"use client";

// AUTO-GENERATED by demo-src/build-demos.js — do not edit by hand; edit the .src.html and re-run.
import { useEffect, useRef } from "react";

const CSS = ${JSON.stringify(css)};
const MARKUP = ${JSON.stringify(markup)};
const SCRIPT = ${JSON.stringify(script)};

export default function ${name}() {
  const ref = useRef<HTMLDivElement>(null);
  const ran = useRef(false);
  useEffect(() => {
    if (ran.current) return;
    ran.current = true;
    try { new Function(SCRIPT)(); } catch (e) { console.error("${name} demo:", e); }
  }, []);
  return (
    <div ref={ref} className=${JSON.stringify(wrapperClass)}
      dangerouslySetInnerHTML={{ __html: "<style>" + CSS + "</style>" + MARKUP }} />
  );
}
`;
}

// ---- CHAT (unscoped -> scope under .cpc-chat) ----
{
  const { css, markup, script } = extract(path.join(HERE, "chat-demo.src.html"));
  const s = scopeCss(css, ".cpc-chat", "cpc_chat");
  const mk = markup.replace(/\.\/card_wa\.jpg/g, "/chat-wa.jpg").replace(/\.\/card_tg\.jpg/g, "/chat-tg.jpg");
  fs.writeFileSync(path.join(COMPONENTS, "chat-demo.tsx"), emit("ChatDemo", "cpc-chat", s, mk, script));
  console.log("wrote components/chat-demo.tsx");
}
// ---- SCAN (already scoped .cp-uscan -> strip global body, use real card photo) ----
{
  const { css, markup, script } = extract(path.join(HERE, "scan-lead.src.html"));
  const s = stripGlobalBody(css);
  const mk = markup.replace(/src="data:image\/jpeg;base64,[^"]*"/, 'src="/chat-wa.jpg"');
  fs.writeFileSync(path.join(COMPONENTS, "scan-lead.tsx"), emit("ScanLead", "", s, mk, script));
  console.log("wrote components/scan-lead.tsx");
}
